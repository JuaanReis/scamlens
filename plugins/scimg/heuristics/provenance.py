"""Metadados de geradores: indícios declarativos, nunca prova criptográfica."""
from plugins.scimg.models.result_base import ResultBase
from .registry import register

# Pares concretos, verificáveis por texto, obtidos APENAS de metadados.
MARKERS = (
    ("stable_diffusion_marker", ("stable diffusion", "stable-diffusion")),
    ("comfyui_marker", ("comfyui", "comfy ui")),
    ("automatic1111_marker", ("automatic1111", "a1111")),
    ("invokeai_marker", ("invokeai",)),
    ("midjourney_marker", ("midjourney",)),
    ("dalle_marker", ("dall-e", "dalle-3", "dall·e")),
    ("firefly_marker", ("adobe firefly",)),
    ("generated_declaration", ("ai generated", "generated by ai", "generado por ia")),
)

def _make_rule(name, markers):
    @register(name=name, category="provenance", severity="high", weight=12.0,
              tags=["image", "metadata", "generator"], group="provenance")
    def check_metadata(data: dict) -> ResultBase:
        raw = data.get("metadata_text", "")
        if not raw:
            return ResultBase(value=0, normalized=None, details={"reason": "metadata_absent"})
        found = [marker for marker in markers if marker in raw]
        return ResultBase(value=len(found), normalized=0.95 if found else None,
                          details={"markers":found, "warning":"Metadados podem ser forjados"})
    check_metadata.__name__ = name
    return check_metadata

for _name,_markers in MARKERS:
    globals()[_name] = _make_rule(_name, _markers)
